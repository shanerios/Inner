// plugins/withFmtConstevalFix.js
//
// React Native 0.81 builds the `fmt` formatting library from source on iOS. Newer Xcode releases
// (seen with Xcode 26.6 / Apple clang 21) reject fmt 11.0.2's compile-time format-string checks with
// "call to consteval function ... is not a constant expression", so the whole iOS build fails.
// The EAS images pin an older Xcode, but local builds on a current Mac fail.
//
// Fix: after the pods are installed, force fmt's FMT_USE_CONSTEVAL to 0 in its base.h. That only turns
// off a compile-time check of format strings; formatting behaviour is unchanged. (Passing
// -DFMT_USE_CONSTEVAL=0 as a compiler flag does not work, because base.h defines it unconditionally.)
//
// ios/ is gitignored and regenerated by `expo prebuild`; this plugin makes the change durable.
const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('@expo/config-plugins');

const MARKER = 'withFmtConstevalFix';
const ANCHOR = 'post_install do |installer|';

const RUBY = `
    # ${MARKER}: newer Xcode rejects fmt's consteval format-string checks; turn them off.
    fmt_base = File.join(installer.sandbox.root.to_s, 'fmt', 'include', 'fmt', 'base.h')
    if File.exist?(fmt_base)
      fmt_source = File.read(fmt_base)
      fmt_patched = fmt_source.gsub(/(#\\s*define FMT_USE_CONSTEVAL) 1\\b/, '\\\\1 0')
      if fmt_patched != fmt_source
        File.chmod(0644, fmt_base)
        File.write(fmt_base, fmt_patched)
      end
    end
`;

/** Returns the Podfile text with the fmt patch added to its first post_install block. */
function addFmtFix(podfile) {
  if (podfile.includes(MARKER)) return podfile; // already applied
  if (!podfile.includes(ANCHOR)) {
    throw new Error(`${MARKER}: could not find "${ANCHOR}" in the Podfile`);
  }
  return podfile.replace(ANCHOR, ANCHOR + RUBY);
}

module.exports = function withFmtConstevalFix(config) {
  return withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const podfilePath = path.join(cfg.modRequest.platformProjectRoot, 'Podfile');
      const podfile = fs.readFileSync(podfilePath, 'utf8');
      fs.writeFileSync(podfilePath, addFmtFix(podfile));
      return cfg;
    },
  ]);
};

module.exports.addFmtFix = addFmtFix;
module.exports.MARKER = MARKER;
